/**
 * @file  test_cmac.c
 * @brief Task 5: AES-CMAC and g2 against their official test vectors.
 *        Written before the implementation.
 *
 * Sources, every vector checked against pyca/cryptography 41.0.7 before
 * being written here:
 * - RFC 4493 section 4 (the same vectors as Core Vol 3 Part H, Appendix D.1)
 * - Core Specification 6.2, Vol 3 Part H, Appendix D.5 (g2) and 2.2.9
 * - Boundary lengths the official vectors skip, generated with
 *   pyca/cryptography: the RFC key over the message 00 01 02 ... 3f.
 */
#include "check.h"
#include "ble/ble_cmac.h"
#include "ble/ble_sc.h"

/** @brief RFC 4493 key, MSB-first. */
static const unsigned char RFC_KEY[16] = {
    0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6,
    0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};

/** @brief RFC 4493 message; the examples use its first 0, 16, 40 and 64 bytes. */
static const unsigned char RFC_MSG[64] = {
    0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a,
    0xae, 0x2d, 0x8a, 0x57, 0x1e, 0x03, 0xac, 0x9c, 0x9e, 0xb7, 0x6f, 0xac, 0x45, 0xaf, 0x8e, 0x51,
    0x30, 0xc8, 0x1c, 0x46, 0xa3, 0x5c, 0xe4, 0x11, 0xe5, 0xfb, 0xc1, 0x19, 0x1a, 0x0a, 0x52, 0xef,
    0xf6, 0x9f, 0x24, 0x45, 0xdf, 0x4f, 0x9b, 0x17, 0xad, 0x2b, 0x41, 0x7b, 0xe6, 0x6c, 0x37, 0x10};

/** @brief One MAC test: message length and expected MAC. */
typedef struct {
    size_t len;             /**< Message length in bytes. */
    unsigned char mac[16];  /**< Expected MAC, MSB-first. */
} cmac_vector_t;

/**
 * @brief AES-CMAC tests.
 *
 * The RFC's subkeys, then its four examples: the empty message (one padded
 * block, K2), exactly one block (K1), 40 bytes (a padded last block after
 * two complete ones), and 64 bytes (four complete blocks). Then the lengths
 * around each block boundary, 1 to 48, which the RFC does not cover.
 */
void suite_cmac(void)
{
    SUITE("aes-cmac (task 5)");
    unsigned char k1[16], k2[16], mac[16];

    /* ---- RFC 4493, section 4: subkey generation -------------------------- */
    static const unsigned char K1[16] = {
        0xfb, 0xee, 0xd6, 0x18, 0x35, 0x71, 0x33, 0x66, 0x7c, 0x85, 0xe0, 0x8f, 0x72, 0x36, 0xa8, 0xde};
    static const unsigned char K2[16] = {
        0xf7, 0xdd, 0xac, 0x30, 0x6a, 0xe2, 0x66, 0xcc, 0xf9, 0x0b, 0xc1, 0x1e, 0xe4, 0x6d, 0x51, 0x3b};
    ble_cmac_subkeys(RFC_KEY, k1, k2);
    CHECK_MEM(k1, K1, 16);
    CHECK_MEM(k2, K2, 16);

    /* ---- RFC 4493, section 4: examples 1 to 4 ---------------------------- */
    static const cmac_vector_t rfc[] = {
        {0,  {0xbb, 0x1d, 0x69, 0x29, 0xe9, 0x59, 0x37, 0x28, 0x7f, 0xa3, 0x7d, 0x12, 0x9b, 0x75, 0x67, 0x46}},
        {16, {0x07, 0x0a, 0x16, 0xb4, 0x6b, 0x4d, 0x41, 0x44, 0xf7, 0x9b, 0xdd, 0x9d, 0xd0, 0x4a, 0x28, 0x7c}},
        {40, {0xdf, 0xa6, 0x67, 0x47, 0xde, 0x9a, 0xe6, 0x30, 0x30, 0xca, 0x32, 0x61, 0x14, 0x97, 0xc8, 0x27}},
        {64, {0x51, 0xf0, 0xbe, 0xbf, 0x7e, 0x3b, 0x9d, 0x92, 0xfc, 0x49, 0x74, 0x17, 0x79, 0x36, 0x3c, 0xfe}},
    };
    for (size_t i = 0; i < sizeof rfc / sizeof rfc[0]; i++) {
        ble_aes_cmac(RFC_KEY, RFC_MSG, rfc[i].len, mac);
        CHECK_MEM(mac, rfc[i].mac, 16);
    }
    /* the empty message may come with no buffer at all */
    ble_aes_cmac(RFC_KEY, NULL, 0, mac);
    CHECK_MEM(mac, rfc[0].mac, 16);

    /* ---- block boundaries: message 00 01 02 ... (pyca/cryptography) ------ */
    unsigned char seq[48];
    for (unsigned i = 0; i < sizeof seq; i++) {
        seq[i] = (unsigned char)i;
    }
    static const cmac_vector_t edges[] = {
        {1,  {0x2b, 0xec, 0xea, 0xa8, 0x1b, 0xbd, 0x0f, 0x09, 0xa2, 0x6b, 0xc4, 0xad, 0x28, 0xb7, 0xdd, 0x18}},
        {15, {0xca, 0x40, 0x88, 0x58, 0x08, 0x0e, 0x7b, 0xd3, 0xb3, 0x3d, 0x01, 0xba, 0xcf, 0x37, 0x19, 0x65}},
        {17, {0x03, 0x9b, 0x52, 0x75, 0xa5, 0xbb, 0x11, 0x1e, 0x9d, 0x2d, 0xaf, 0x0c, 0x79, 0x44, 0x2e, 0xa1}},
        {31, {0xd4, 0x79, 0x82, 0x30, 0xbf, 0x11, 0x30, 0x79, 0x00, 0xdb, 0x0f, 0x02, 0x66, 0x14, 0x5a, 0xb9}},
        {32, {0xe9, 0x08, 0x5e, 0x5b, 0x1c, 0xeb, 0x86, 0x1c, 0xd0, 0x0b, 0x0b, 0xf7, 0x2f, 0xf5, 0x11, 0x1b}},
        {33, {0x5e, 0x86, 0x94, 0x65, 0xd9, 0x2a, 0x47, 0xf1, 0x78, 0x38, 0xb2, 0x52, 0x49, 0x5e, 0x38, 0x34}},
        {48, {0xb4, 0x6d, 0xd8, 0x85, 0x6c, 0x4f, 0xee, 0x71, 0x3a, 0x92, 0x43, 0xe9, 0x17, 0xf1, 0xfd, 0xb7}},
    };
    for (size_t i = 0; i < sizeof edges / sizeof edges[0]; i++) {
        ble_aes_cmac(RFC_KEY, seq, edges[i].len, mac);
        CHECK_MEM(mac, edges[i].mac, 16);
    }
}

/**
 * @brief g2 tests: the Appendix D.5 vector end to end, and the six-digit
 *        value both the vector and the example in section 2.2.9 produce.
 */
void suite_sc(void)
{
    SUITE("le secure connections g2 (task 5)");

    /* ---- Core 6.2, Vol 3 Part H, Appendix D.5 ---------------------------- */
    static const unsigned char U[32] = {        /* PKax */
        0x20, 0xb0, 0x03, 0xd2, 0xf2, 0x97, 0xbe, 0x2c, 0x5e, 0x2c, 0x83, 0xa7, 0xe9, 0xf9, 0xa5, 0xb9,
        0xef, 0xf4, 0x91, 0x11, 0xac, 0xf4, 0xfd, 0xdb, 0xcc, 0x03, 0x01, 0x48, 0x0e, 0x35, 0x9d, 0xe6};
    static const unsigned char V[32] = {        /* PKbx */
        0x55, 0x18, 0x8b, 0x3d, 0x32, 0xf6, 0xbb, 0x9a, 0x90, 0x0a, 0xfc, 0xfb, 0xee, 0xd4, 0xe7, 0x2a,
        0x59, 0xcb, 0x9a, 0xc2, 0xf1, 0x9d, 0x7c, 0xfb, 0x6b, 0x4f, 0xdd, 0x49, 0xf4, 0x7f, 0xc5, 0xfd};
    static const unsigned char X[16] = {        /* Na */
        0xd5, 0xcb, 0x84, 0x54, 0xd1, 0x77, 0x73, 0x3e, 0xff, 0xff, 0xb2, 0xec, 0x71, 0x2b, 0xae, 0xab};
    static const unsigned char Y[16] = {        /* Nb */
        0xa6, 0xe8, 0xe7, 0xcc, 0x25, 0xa7, 0x5f, 0x6e, 0x21, 0x65, 0x83, 0xf7, 0xff, 0x3d, 0xc4, 0xcf};

    uint32_t g2 = ble_sc_g2(U, V, X, Y);
    CHECK_EQ(g2, 0x2f9ed5bau);
    CHECK_EQ(ble_sc_compare_value(g2), 938554u);    /* what both screens show */

    /* swapping the two keys is a different pairing: a different number */
    CHECK(ble_sc_g2(V, U, X, Y) != g2);

    /* ---- Core 6.2, Vol 3 Part H, 2.2.9: the worked example ---------------- */
    CHECK_EQ(ble_sc_compare_value(0x012eb72au), 838762u);
    CHECK_EQ(ble_sc_compare_value(0u), 0u);
    CHECK_EQ(ble_sc_compare_value(0xffffffffu), 967295u);   /* 4294967295 */
}
